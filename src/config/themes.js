/**
 * Centralized Themes Configuration for Mimicu
 *
 * Exactly TWO top-level theme categories:
 * - [ Glass ] (8 themes): Glass Dark, Glass Light, Glass Smoke, Glass Night, Frost Light, Frost Dark, Rose Glass, Ocean Glass
 * - [ Solid ] (12 themes): Solid Black, Solid Navy, Solid Forest, Solid Plum, Solid Burgundy, Solid Ocean, Solid Amber, Solid Ivory, Solid Cream, Solid Sage, Solid Rose, Solid Sand
 *
 * Mode ('dark' | 'light') is an internal attribute.
 * Type ('glass' | 'solid') controls surface opacity, backdrop blur, and layering.
 */

function defineTheme({
  id,
  name,
  type, // 'glass' | 'solid'
  mode, // 'dark' | 'light'
  previewColors,
  tokens: raw,
}) {
  const isGlass = type === 'glass';
  const isLight = mode === 'light';

  return {
    id,
    name,
    type,
    mode,
    previewColors,
    tokens: {
      // ── Backgrounds & Surfaces ──
      background: raw.background,
      backgroundSecondary: raw.backgroundSecondary || raw.background,
      backgroundElevated: raw.backgroundElevated || raw.surfaceElevated || raw.backgroundSecondary || raw.background,
      surface: raw.surface,
      surfaceSecondary: raw.surfaceSecondary || raw.surfaceElevated || raw.surface,
      surfaceElevated: raw.surfaceElevated || raw.surface,
      surfaceHover: raw.surfaceHover || raw.surfaceElevated || raw.surface,
      card: raw.card || raw.surface,
      cardHover: raw.cardHover || raw.surfaceHover || raw.surfaceElevated,

      // ── Typography & Icons ──
      textPrimary: raw.textPrimary,
      textSecondary: raw.textSecondary,
      textMuted: raw.textMuted,
      iconPrimary: raw.iconPrimary || raw.textPrimary,
      iconSecondary: raw.iconSecondary || raw.accent,

      // ── Accent & Glow ──
      accent: raw.accent,
      accentSecondary: raw.accentSecondary || raw.accent,
      accentHover: raw.accentHover || raw.accent,
      accentText: raw.accentText || (isLight ? '#ffffff' : '#000000'),
      accentGlow: raw.accentGlow || `${raw.accent}55`,

      // ── Borders ──
      border: raw.border,
      borderStrong: raw.borderStrong || raw.accent,

      // ── Shadows ──
      shadow: raw.shadow || (isLight ? 'rgba(0, 0, 0, 0.08)' : 'rgba(0, 0, 0, 0.35)'),
      shadowStrong: raw.shadowStrong || (isLight ? 'rgba(0, 0, 0, 0.16)' : 'rgba(0, 0, 0, 0.65)'),

      // ── Buttons ──
      buttonPrimary: raw.buttonPrimary || raw.accent,
      buttonPrimaryText: raw.buttonPrimaryText || (isLight ? '#ffffff' : '#000000'),
      buttonPrimaryHover: raw.buttonPrimaryHover || raw.accentHover || raw.accent,
      buttonSecondary: raw.buttonSecondary || raw.surfaceElevated || raw.surface,
      buttonSecondaryText: raw.buttonSecondaryText || raw.textPrimary,
      buttonSecondaryHover: raw.buttonSecondaryHover || raw.surfaceHover,
      buttonGhost: raw.buttonGhost || 'transparent',
      buttonGhostText: raw.buttonGhostText || raw.textSecondary,
      buttonGhostHover: raw.buttonGhostHover || raw.buttonSecondary,

      // ── Inputs ──
      input: raw.input || raw.surface,
      inputText: raw.inputText || raw.textPrimary,
      inputPlaceholder: raw.inputPlaceholder || raw.textMuted,
      inputBorder: raw.inputBorder || raw.border,

      // ── Navigation & Dock ──
      navigation: raw.navigation || raw.backgroundSecondary || raw.surface,
      navigationText: raw.navigationText || raw.textSecondary,
      navigationActive: raw.navigationActive || raw.textPrimary,
      navigationInactive: raw.navigationInactive || raw.textMuted,

      // ── Player ──
      player: raw.player || raw.playerBackground || raw.navigation,
      playerBackground: raw.playerBackground || raw.player || raw.navigation,
      playerBorder: raw.playerBorder || raw.border,
      playerText: raw.playerText || raw.textPrimary,

      // ── Glass & Solid Specifics ──
      glassOpacity: raw.glassOpacity || (isGlass ? '0.45' : '1.0'),
      glassBlur: raw.glassBlur || (isGlass ? '24px' : '0px'),
      glassBorder: raw.glassBorder || raw.border,
      glass: raw.glass || raw.surface,
      glassStrong: raw.glassStrong || raw.surfaceElevated || raw.surface,
      modalBackground: raw.modalBackground || (isGlass ? (isLight ? 'rgba(255, 255, 255, 0.82)' : 'rgba(16, 22, 36, 0.78)') : raw.surfaceElevated || raw.surface),

      // ── Focus & Overlay ──
      focusRing: raw.focusRing || raw.accent,
      overlay: raw.overlay || (isLight ? 'rgba(15, 23, 42, 0.50)' : 'rgba(0, 0, 0, 0.70)'),
      overlayBg: raw.overlayBg || raw.overlay,
    },
  };
}

